import { readFileSync, writeFileSync } from 'node:fs';
for (const [name, expectedExports] of [['forecast-lookup',4],['account-sync-client',1]]) {
const source = new URL(`../src/${name}.js`, import.meta.url);
const target = new URL(`../miniprogram/core/${name}.js`, import.meta.url);
const text = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const names = [...text.matchAll(/^export function (\w+)/gm)].map(match => match[1]);
if (names.length !== expectedExports || /^(?:import|export (?!function))/m.test(text)) throw new Error('unsupported_shared_module');
const output = `// Generated by scripts/build-mini-shared.mjs. Edit src/${name}.js.\n` + text.replace(/^export /gm, '') + `\nmodule.exports = { ${names.join(', ')} };\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('mini_shared_module_drift');
} else writeFileSync(target, output);
}
