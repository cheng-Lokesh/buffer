import { readFileSync, writeFileSync } from 'node:fs';
const source = new URL('../src/forecast-lookup.js', import.meta.url);
const target = new URL('../miniprogram/core/forecast-lookup.js', import.meta.url);
const text = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const names = [...text.matchAll(/^export function (\w+)/gm)].map(match => match[1]);
if (names.length !== 4 || /^(?:import|export (?!function))/m.test(text)) throw new Error('unsupported_shared_module');
const output = '// Generated by scripts/build-mini-shared.mjs. Edit src/forecast-lookup.js.\n' + text.replace(/^export /gm, '') + `\nmodule.exports = { ${names.join(', ')} };\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('mini_shared_module_drift');
} else writeFileSync(target, output);
